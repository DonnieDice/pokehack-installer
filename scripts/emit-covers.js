// Emits src/data/covers.js from src/data/hacks.js so every hack id always
// has a local fallback cover wired into the bundle. Run after adding hacks:
//   node scripts/emit-covers.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'src/data/hacks.js'), 'utf8');
const ids = [];
for (const m of src.matchAll(/id: '([^']+)',/g)) {
  if (m.index !== undefined && src.slice(Math.max(0, m.index - 200), m.index).includes('export const HACKS') || true) {
    ids.push(m[1]);
  }
}
// Only ids inside the HACKS array (before 'export const PLATFORMS')
const hacksPart = src.split('export const PLATFORMS')[0];
const finalIds = [];
for (const m of hacksPart.matchAll(/id: '([^']+)',/g)) finalIds.push(m[1]);
const seen = new Set();
const lines = [
  '// Auto-generated by scripts/emit-covers.js from src/data/hacks.js.',
  '// Static require map so Metro bundles every fallback cover; real remote',
  '// art lives in each hack.coverUrl, this is the offline/error fallback.',
  'export const COVERS = {',
];
for (const id of finalIds) {
  if (seen.has(id)) continue;
  seen.add(id);
  lines.push(`  ${/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(id) ? id : `'${id}'`}: require('../../assets/covers/${id}.png'),`);
}
lines.push('};');
lines.push('');
fs.writeFileSync(path.join(root, 'src/data/covers.js'), lines.join('\n'));
console.log('covers.js: ' + seen.size + ' entries');
